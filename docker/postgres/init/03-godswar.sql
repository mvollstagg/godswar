-- Views
CREATE OR REPLACE VIEW godswar.view_consortia AS
SELECT
    cb.name AS role_name,
    cb.scholar_job_lv AS s_lv,
    cb.fighter_job_lv AS f_lv,
    cb.consortia_job,
    cb.map AS map_id,
    cb.consortia AS consortia_id,
    c.name,
    cb.profession,
    cb.consortia_contribute AS contribute
FROM godswar.character_base cb
JOIN godswar.consortia c ON cb.consortia = c.id;

CREATE OR REPLACE VIEW accounts.view_web_select_lv AS
SELECT DISTINCT
    ai.accounts,
    cb.name AS role_name,
    cb.fighter_job_lv AS f_lv,
    cb.scholar_job_lv AS s_lv
FROM accounts.accounts_info ai
JOIN godswar.character_base cb ON ai.accounts = cb.accounts;
