-- GodsWar Online: accounts schema (converted from accounts.sql)

CREATE TABLE IF NOT EXISTS accounts.accounts_ban (
    id integer PRIMARY KEY,
    bandate timestamp NOT NULL,
    unbandate timestamp NOT NULL,
    bannedby varchar(50) NOT NULL,
    banreason varchar(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS accounts.accounts_info (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    accounts varchar(32) NOT NULL UNIQUE,
    password varchar(32) NOT NULL,
    login_status smallint NOT NULL DEFAULT 0,
    last_login_time timestamp NOT NULL DEFAULT NOW(),
    last_logout_time timestamp NOT NULL DEFAULT NOW(),
    last_login_ip varchar(20) NOT NULL DEFAULT '',
    last_login_mac varchar(50) NOT NULL DEFAULT '',
    total_online_time bigint NOT NULL DEFAULT 0,
    accounts_status smallint NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS accounts.accounts_register (
    acc_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pass_name varchar(32),
    pass_pwd varchar(32),
    identity_id varchar(255),
    real_name varchar(255),
    email varchar(255),
    question varchar(255),
    answer varchar(255),
    regedit_time timestamp,
    area_id varchar(50),
    active_number varchar(50),
    is_active smallint,
    is_del smallint
);

CREATE TABLE IF NOT EXISTS accounts.gamearea_info (
    gid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_area integer NOT NULL DEFAULT 1,
    acc_id integer NOT NULL DEFAULT 0,
    pass_name varchar(255) NOT NULL UNIQUE,
    pass_pwd varchar(255) NOT NULL,
    balance varchar(255),
    is_del smallint NOT NULL DEFAULT 0,
    is_draw smallint DEFAULT 0
);

CREATE TABLE IF NOT EXISTS accounts.ip_ban (
    ip varchar(32) PRIMARY KEY,
    bandate timestamp NOT NULL,
    unbandate timestamp NOT NULL,
    bannedby varchar(50) NOT NULL,
    banreason varchar(255) NOT NULL
);
